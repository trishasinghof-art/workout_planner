export function getMockDietPlan(dietType = "Vegetarian", goal = "maintenance") {
  const normalizedDietType = dietType.toLowerCase();
  const normalizedGoal = goal ? goal.toLowerCase() : 'maintenance';
  const isVegetarian = !normalizedDietType.includes('non') && !normalizedDietType.includes('meat');

  let baseDiet;

  if (normalizedGoal.includes('loss') || normalizedGoal.includes('cut')) {
    baseDiet = mockWeightLossDiet;
  } else if (normalizedGoal.includes('gain') || normalizedGoal.includes('bulk') || normalizedGoal.includes('muscle')) {
    baseDiet = mockMuscleGainDiet;
  } else {
    baseDiet = isVegetarian ? mockVegetarianDiet : mockNonVegetarianDiet;
  }

  if (isVegetarian && (baseDiet === mockWeightLossDiet || baseDiet === mockMuscleGainDiet)) {
    const veganizedDiet = {
      ...baseDiet,
      dietType: "Vegetarian",
      meals: baseDiet.meals.map(meal => ({
        ...meal,
        items: meal.items.map(item => 
          item
            .replace(/chicken/gi, 'paneer')
            .replace(/turkey/gi, 'tofu')
            .replace(/salmon/gi, 'chickpeas')
            .replace(/tuna/gi, 'lentils')
            .replace(/egg white/gi, 'tofu scramble')
            .replace(/eggs/gi, 'tofu')
            .replace(/Greek yogurt \(non-fat\)/gi, 'Greek yogurt')
            .replace(/protein shake with whey/gi, 'protein shake with plant protein')
        )
      }))
    };
    return veganizedDiet;
  }

  return {
    ...baseDiet,
    dietType: isVegetarian ? "Vegetarian" : "Non-Vegetarian"
  };
}
